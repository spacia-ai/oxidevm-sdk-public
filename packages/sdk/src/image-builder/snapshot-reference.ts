import type {SnapshotBundleIndex} from "./snapshot-index.js";
export const SNAPSHOT_REFERENCE_MARKER="// Generated by OxideVM snapshot authoring.\n";
function at(base:string,path:string):string {
  const location=new URL(path,new URL(base,"https://oxidevm-reference.invalid/"));
  return base.startsWith("/")?`${location.pathname}${location.search}`:location.href;
}
/** A pure constructor-only module, reproducible from the signed index and hosting base. */
export function snapshotReferenceSource(index:SnapshotBundleIndex,base=index.publicBaseUrl):string {
  const image={...index.image,manifestUrl:at(base,"image/manifest.json")};
  const shipped={mode:index.mode,name:index.name,manifestUrl:at(base,index.snapshot.url),manifestSHA256:index.snapshot.sha256,
    manifestBytes:index.snapshot.bytes,downloadBytes:index.snapshot.downloadBytes,imageManifestSHA256:index.image.manifestSHA256,trust:index.trust};
  const type=index.mode==="system"?"SystemOptions":"UserspaceOptions";
  const resources=JSON.stringify(index.vm,null,2).slice(1,-1).trim();
  return `${SNAPSHOT_REFERENCE_MARKER}import { defineImage, defineShippedSnapshot } from "@oxidevm/sdk";\nimport type { ${type} } from "@oxidevm/sdk";\nconst image = defineImage(${JSON.stringify(image,null,2)});\nconst shipped = defineShippedSnapshot(${JSON.stringify(shipped,null,2)});\nexport default {\n  ${resources},\n  mode: ${JSON.stringify(index.mode)}, image, shippedSnapshot: shipped, restorePoint: "latest",\n} satisfies ${type};\n`;
}
