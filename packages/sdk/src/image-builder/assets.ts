export interface InstallAssetsOptions {
  /** Frame hosting stages image assets without installing a local engine. Omission preserves explicit self-hosted installation. */
  readonly hosting?: "frame" | "self-hosted";
  readonly imageDir?: string;
  readonly snapshotDir?:string;
  readonly referencePath?: string;
  readonly trust?: TrustedImageKey;
  readonly imageCacheDir?: string;
  /**
   * A local copy of the SDK's pinned engine release, relative to the project directory. Without it
   * the release comes from OXIDEVM_ENGINE_DIR, the engine cache, or the private release channel
   * (with OXIDEVM_DOWNLOAD_TOKEN); every source is verified against the pin.
   */
  readonly engineDir?: string;
  readonly engineComplianceDir?: string;
  readonly signal?: AbortSignal;
}
export interface InstallAssetsResult { readonly publicDir: string; readonly files: number; readonly referencePath: string | null }
const generatedMarker = "// Generated by OxideVM assets install.\n";

export function defaultImageCacheDir(): string {
  return resolve(process.env["XDG_CACHE_HOME"] ?? join(homedir(), ".cache"), "oxidevm/images");
}

/** Public starters admit only the exact signed distribution closure pinned by the CLI release. */
export async function downloadImageBundle(archive: { readonly url: string; readonly bytes: number; readonly sha256: string }, image: ImageRef<"userspace">, options: { readonly cacheDir?: string; readonly signal?: AbortSignal } = {}): Promise<string> {
  const target = join(options.cacheDir ?? defaultImageCacheDir(), image.manifestSHA256);
  const verify = async (directory: string) => {
    const inspected = await inspectImageFiles(directory, { trust: image.trust, ...(options.signal === undefined ? {} : { signal: options.signal }) });
    if (inspected.read.image.manifestSHA256 !== image.manifestSHA256 || inspected.read.image.mode !== image.mode) throw new VMError("PROTOCOL_ERROR", "starter archive differs from its pinned image");
    await validateDistributionBundle(inspected.read, options.signal);
  };
  if (await lstat(target).catch(() => undefined) === undefined) await downloadBundle(archive, target, verify, options.signal);
  else await verify(target);
  return target;
}

/** Validate each existing output ancestor; staging cannot follow a project symlink. */
export async function checkedOutput(root: string, relative: string): Promise<string> {
  const path = resolve(root, relative);
  if (path !== root && !path.startsWith(`${root}${sep}`)) throw new VMError("INVALID_ARGUMENT", "asset output escapes its selected directory");
  const parts = path.slice(root.length).split(sep).filter(Boolean);
  let current = root;
  for (const part of ["", ...parts]) {
    if (part !== "") current = join(current, part);
    const metadata = await lstat(current).catch((error: unknown) => {
      if (typeof error === "object" && error !== null && "code" in error && error.code === "ENOENT") return undefined;
      throw error;
    });
    if (metadata?.isSymbolicLink() === true) throw new VMError("PERMISSION_DENIED", "asset output must not follow symlinks");
  }
  return path;
}

export async function installStaticAssets(source: string, target: string, signal?: AbortSignal): Promise<number> {
  let count = 0;
  await atomicBundle(target, async staging => {
    async function copy(relative: string): Promise<void> {
      for (const entry of await readdir(join(source, relative), { withFileTypes: true })) {
        const path = relative === "" ? entry.name : `${relative}/${entry.name}`;
        if (entry.isDirectory()) await copy(path);
        else if (entry.isFile() && !path.endsWith(".map")) {
          const file = await localBundlePath(source, path);
          await copyVerified(file, join(staging, path), { bytes: (await lstat(file)).size, sha256: await hashFile(file, signal) }, signal); count += 1;
        } else if (!entry.isFile()) throw new VMError("PROTOCOL_ERROR", "platform static assets must not contain symlinks");
      }
    }
    await copy("");
  }, signal);
  return count;
}

/**
 * An existing application starts with only `oxidevm.config.ts`: its first install writes the lock
 * `oxidevm init` would. An existing lock is validated, never replaced.
 */
async function readProjectLock(directory: string, config: ProjectConfig, signal?: AbortSignal): Promise<Uint8Array<ArrayBuffer>> {
  const path = join(directory, "oxidevm.lock.json");
  const present = await lstat(path).then(() => true, (error: unknown) => {
    if (typeof error === "object" && error !== null && "code" in error && error.code === "ENOENT") return false;
    throw error;
  });
  // Exclusive creation: a lock written concurrently fails loudly instead of being overwritten.
  if (!present) await writeFile(path, `${JSON.stringify(createProjectLock(config), null, 2)}\n`, { flag: "wx" });
  return readBundleFile(directory, "oxidevm.lock.json", 1024 ** 2, signal);
}

async function selectProjectImage(directory: string, config: ResolvedProjectConfig, options: InstallAssetsOptions): Promise<{ readonly config: ResolvedProjectConfig; readonly inspected?: InspectedImageFiles }> {
  if (options.imageDir === undefined) return { config };
  const trust = options.trust ?? config.image?.trust;
  const inspected = await inspectImageFiles(resolve(directory, options.imageDir), { ...(trust === undefined ? {} : { trust }), ...(options.signal === undefined ? {} : { signal: options.signal }) });
  const image = inspected.read.image;
  if (image.mode !== config.mode) throw new VMError("INVALID_ARGUMENT", "image bundle must match the selected project mode");
  if (config.image !== undefined && (image.manifestSHA256 !== config.image.manifestSHA256 || image.trust.publicKey !== config.image.trust.publicKey || image.trust.keyId !== config.image.trust.keyId)) {
    throw new VMError("INVALID_ARGUMENT", "image bundle differs from the explicitly configured image");
  }
  if (trust === undefined) await inspectImageFiles(inspected.read.bundle, { trust: image.trust, ...(options.signal === undefined ? {} : { signal: options.signal }) });
  const selected = config.image ?? { mode: image.mode, trust: image.trust, manifestSHA256: image.manifestSHA256, manifestUrl: `${config.assetBaseUrl}images/${image.manifestSHA256}/manifest.json` };
  return { config: decodeProjectConfig({ ...config, image: selected }), inspected };
}

/** Stage the authenticated image closure and, for explicit self-hosting, its pinned engine. */
export async function installProjectAssets(projectDir: string, input: ProjectConfig, options: InstallAssetsOptions = {}): Promise<InstallAssetsResult> {
  const directory = resolve(projectDir); abortIfRequested(options.signal);
  const hosting: unknown = options.hosting;
  if (hosting !== undefined && hosting !== "frame" && hosting !== "self-hosted") throw new VMError("INVALID_ARGUMENT", "asset hosting must be frame or self-hosted");
  if (options.snapshotDir !== undefined && options.imageDir !== undefined) throw new VMError("INVALID_ARGUMENT", "Select one image or snapshot bundle");
  if (options.hosting === "frame" && (options.engineDir !== undefined || options.engineComplianceDir !== undefined || options.snapshotDir !== undefined)) throw new VMError("INVALID_ARGUMENT", "frame asset staging cannot install an engine or a self-hosted snapshot");
  const selected = await selectProjectImage(directory, decodeProjectConfig(input), options);
  const config = selected.config;
  const lock = validateProjectLock(decodeBundleJSON(await readProjectLock(directory, config, options.signal)), config);
  if(options.snapshotDir!==undefined){
    return installSnapshotAssets(directory,config,lock,options);
  }
  if (options.referencePath !== undefined && options.imageDir === undefined) throw new VMError("INVALID_ARGUMENT", "a custom reference requires a custom image bundle");
  // Only self-hosted installation resolves engine files; frame staging keeps image verification.
  const engine = pinnedEngineRelease();
  const engineDir = options.hosting === "frame" ? undefined : await resolveEngineDirectory({ ...(options.engineDir === undefined ? {} : { engineDir: resolve(directory, options.engineDir) }), ...(options.engineComplianceDir === undefined ? {} : { engineComplianceDir: resolve(directory, options.engineComplianceDir) }), ...(options.signal === undefined ? {} : { signal: options.signal }) }, engine);
  const source = options.imageDir === undefined ? join(options.imageCacheDir ?? defaultImageCacheDir(), lock.image.manifestSHA256) : resolve(directory, options.imageDir);
  if (options.imageDir === undefined && await lstat(source).catch(() => undefined) === undefined) {
    const catalog = await readReleaseCatalog();
    const entry = catalog.images.find(image => image.mode === config.mode && image.manifestSHA256 === lock.image.manifestSHA256);
    if (catalog.schemaVersion === 3) throw new VMError("FEATURE_NOT_AVAILABLE", "Supply a local image bundle with assets install --image");
    if (catalog.sdkVersion !== lock.sdkVersion || entry === undefined) throw new VMError("PROTOCOL_ERROR", "release catalog does not contain the exact project image");
    await downloadBundle(entry.archive, source, async staging => {
      const image = await inspectImageFiles(staging, { trust: lock.image.trust, ...(options.signal === undefined ? {} : { signal: options.signal }) });
      if (image.read.image.manifestSHA256 !== lock.image.manifestSHA256 || image.read.image.mode !== config.mode) throw new VMError("PROTOCOL_ERROR", "downloaded image differs from its pinned release");
    }, options.signal);
  }
  const trust = options.trust ?? config.image?.trust ?? (options.imageDir === undefined ? lock.image.trust : undefined);
  const inspected = selected.inspected ?? await inspectImageFiles(source, { ...(trust === undefined ? {} : { trust }), ...(options.signal === undefined ? {} : { signal: options.signal }) });
  if (inspected.read.image.mode !== config.mode || options.imageDir === undefined && inspected.read.image.manifestSHA256 !== lock.image.manifestSHA256) throw new VMError("PROTOCOL_ERROR", "image bundle does not match the selected mode and release pin");
  // An explicitly selected local custom bundle is author input. Check its claimed
  // signature too; only the separate caller-supplied trust anchor authenticates it.
  if (trust === undefined) await inspectImageFiles(source, { trust: inspected.read.image.trust, ...(options.signal === undefined ? {} : { signal: options.signal }) });
  const publicDir = resolve(directory, config.publicDir);
  await checkedOutput(directory, config.publicDir); await mkdir(publicDir, { recursive: true });
  const base = new URL(config.assetBaseUrl, "https://project.invalid");
  const basePath = decodeURIComponent(base.pathname).replace(/^\/+|\/+$/gu, "");
  const assets = await checkedOutput(publicDir, basePath); await mkdir(assets, { recursive: true });
  const location = new URL(lock.image.manifestUrl, "https://project.invalid");
  if (location.origin !== base.origin || !location.pathname.startsWith(base.pathname)) throw new VMError("INVALID_ARGUMENT", "staged image must be inside the project asset base");
  const imageRelative = decodeURIComponent(location.pathname.slice(base.pathname.length)).replace(/\/manifest\.json$/u, "");
  const imageDirectory = await checkedOutput(assets, imageRelative);
  await mkdir(imageDirectory, { recursive: true });
  for (const file of inspected.files) {
    const target = await checkedOutput(imageDirectory, file.relative);
    const present = await lstat(target).catch(() => undefined);
    if (present !== undefined) {
      if (!present.isFile() || present.size !== file.bytes || await hashFile(target, options.signal) !== file.sha256) throw new VMError("PROTOCOL_ERROR", "immutable staged image differs from its pinned bytes");
    } else await copyVerified(await localBundlePath(source, file.relative), target, file, options.signal);
  }
  const engineFiles = engineDir === undefined ? 0 : await copyEngineRelease(engineDir, await checkedOutput(assets, "runtime"), engine, options.signal, options.engineComplianceDir === undefined ? undefined : resolve(directory, options.engineComplianceDir));
  const doctorFiles = await installStaticAssets(fileURLToPath(new URL("../../assets/doctor/", import.meta.url)), await checkedOutput(assets, "doctor"), options.signal);
  let referencePath: string | null = null;
  if (options.referencePath !== undefined) {
    referencePath = await checkedOutput(directory, options.referencePath);
    const old = await readFile(referencePath, "utf8").catch((error: unknown) => {
      if (typeof error === "object" && error !== null && "code" in error && error.code === "ENOENT") return undefined;
      throw error;
    });
    if (old !== undefined && !old.startsWith(generatedMarker)) throw new VMError("PERMISSION_DENIED", "reference path contains an existing author file");
    const original = inspected.read.image;
    const reference = defineImage({ mode: original.mode, trust: original.trust, manifestSHA256: original.manifestSHA256, manifestUrl: `${config.assetBaseUrl}${imageRelative}/manifest.json` });
    const text = `${generatedMarker}import { defineImage } from "@oxidevm/sdk";\nexport default defineImage(${JSON.stringify({ mode: reference.mode, trust: reference.trust, manifestSHA256: reference.manifestSHA256, manifestUrl: reference.manifestUrl }, null, 2)});\n`;
    await mkdir(dirname(referencePath), { recursive: true }); const temporary = `${referencePath}.installing-${randomUUID()}`;
    try { await writeFile(temporary, text, { flag: "wx" }); abortIfRequested(options.signal); await rename(temporary, referencePath); }
    finally { await rm(temporary, { force: true }); }
  }
  // Bind the deployed doctor to the generated owner, rather than a second version table.
  await writeFile(join(assets, "project.json"), `${JSON.stringify({ schemaVersion: 2, engineRelease: lock.engineRelease, assetBaseUrl: config.assetBaseUrl, mode: config.mode }, null, 2)}\n`);
  return { publicDir, files: inspected.files.length + engineFiles + doctorFiles + 1, referencePath };
}

/** Seed a content-addressed local cache from separately distributed, externally trusted guest bytes. */
export async function cacheImageBundle(bundleDir: string, trust: TrustedImageKey, cacheDir = defaultImageCacheDir(), signal?: AbortSignal): Promise<string> {
  const inspected = await inspectImageFiles(bundleDir, { trust, ...(signal === undefined ? {} : { signal }) });
  const out = join(cacheDir, inspected.read.image.manifestSHA256);
  await atomicBundle(out, async staging => {
    for (const file of inspected.files) await copyVerified(await localBundlePath(inspected.read.bundle, file.relative), join(staging, file.relative), file, signal);
    // No recipe, generated source, signing key, or unreferenced build output enters this cache.
    if (await hashFile(await localBundlePath(staging, "manifest.json"), signal) !== inspected.read.image.manifestSHA256) throw new VMError("PROTOCOL_ERROR", "cached image manifest changed");
  }, signal);
  return out;
}
