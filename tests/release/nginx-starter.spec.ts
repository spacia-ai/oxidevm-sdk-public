import { expect, test } from "@playwright/test";

test("the starter runs, edits and restarts a real Linux server", async ({ page }) => {
  const origin = process.env["OXIDEVM_STARTER_URL"];
  if (origin === undefined) throw new Error("Set OXIDEVM_STARTER_URL to the staged starter application");
  const errors: string[] = [];
  page.on("pageerror", error => { errors.push(error.message); });
  await page.goto(origin, { waitUntil: "domcontentloaded" });
  await expect(page.getByRole("heading", { name: "Your starter app." })).toBeVisible();
  await expect(page.locator("#state")).toHaveText("Running", { timeout: 120_000 });
  const guest = page.frameLocator("#preview");
  await expect(guest.getByRole("heading", { name: "Welcome to nginx." })).toBeVisible({ timeout: 30_000 });
  await expect(page.locator("#response")).toHaveText("200 OK");
  await expect(page.locator("#binary")).toHaveText("ELF 64-bit · x86-64");
  await page.getByRole("button", { name: "Edit this page" }).click();
  await expect(page.locator("#editor")).toBeVisible();
  const original = await page.locator("#html").inputValue();
  await page.locator("#html").fill(original.replace("Welcome to nginx", "Hello from my Linux server"));
  await page.getByRole("button", { name: "Save & reload" }).click();
  await expect(guest.getByRole("heading", { name: "Hello from my Linux server." })).toBeVisible();
  await page.getByRole("button", { name: "Close editor" }).click();
  await page.getByRole("button", { name: "Stop", exact: true }).click();
  await expect(page.locator("#state")).toHaveText("Stopped");
  await expect(page.locator("#preview")).toBeHidden();
  await page.getByRole("button", { name: "Start", exact: true }).click();
  await expect(page.locator("#state")).toHaveText("Running");
  await expect(guest.getByRole("heading", { name: "Hello from my Linux server." })).toBeVisible();
  await page.reload({ waitUntil: "domcontentloaded" });
  await expect(page.locator("#state")).toHaveText("Running", { timeout: 120_000 });
  await expect(guest.getByRole("heading", { name: "Hello from my Linux server." })).toBeVisible();
  await page.getByRole("button", { name: "Reset demo" }).click();
  await page.getByRole("button", { name: "Keep my changes" }).click();
  await expect(guest.getByRole("heading", { name: "Hello from my Linux server." })).toBeVisible();
  await page.getByRole("button", { name: "Reset demo" }).click();
  await page.getByRole("button", { name: "Reset page", exact: true }).click();
  await expect(guest.getByRole("heading", { name: "Welcome to nginx." })).toBeVisible();
  await page.getByRole("button", { name: "Reset demo" }).click();
  await page.keyboard.press("Escape");
  await expect(page.getByRole("dialog")).toBeHidden();
  await expect(page.locator("#terminal .xterm-screen")).toBeVisible();
  await page.locator(".terminal-panel summary").focus();
  await page.getByRole("button", { name: "Focus terminal" }).click();
  await page.keyboard.type("printf 'starter-%s-ok\\n' pty\n");
  await expect.poll(() => page.locator("#terminal .xterm-accessibility-tree").textContent()).toContain("starter-pty-ok");
  await page.keyboard.type("printf 'before-%s\\n' sleep; sleep 30\n");
  await expect.poll(() => page.locator("#terminal .xterm-accessibility-tree").textContent()).toContain("before-sleep");
  await page.getByRole("button", { name: "Send Ctrl+C" }).click();
  await page.getByRole("button", { name: "Focus terminal" }).click();
  await page.keyboard.type("printf 'after-%s\\n' interrupt\n");
  await expect.poll(() => page.locator("#terminal .xterm-accessibility-tree").textContent()).toContain("after-interrupt");
  await page.keyboard.type("set -- $(stty size); printf 'geometry:%s:%s\\n' \"$1\" \"$2\"\n");
  const geometry = () => page.locator("#terminal .xterm-accessibility-tree").textContent();
  await expect.poll(geometry).toMatch(/geometry:[1-9][0-9]*:[1-9][0-9]*/u);
  const previous = /geometry:[1-9][0-9]*:([1-9][0-9]*)/u.exec(await geometry() ?? "")?.[1];
  expect(previous).toBeDefined();
  await page.setViewportSize({ width: 1000, height: 1000 });
  await page.getByRole("button", { name: "Focus terminal" }).click();
  await page.keyboard.type("set -- $(stty size); printf 'resized:%s:%s\\n' \"$1\" \"$2\"\n");
  await expect.poll(geometry).toMatch(/resized:[1-9][0-9]*:[1-9][0-9]*/u);
  const resized = /resized:[1-9][0-9]*:([1-9][0-9]*)/u.exec(await geometry() ?? "")?.[1];
  expect(resized).not.toBe(previous);
  expect(errors).toEqual([]);
});
