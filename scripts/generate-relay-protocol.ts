// The TypeScript half of the engine's relay protocol 2 generator. spec/relay/v2.json is an exact
// copy of the engine's specification; the engine generator owns the Rust relay outputs.
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const input: unknown = JSON.parse(await readFile(resolve(root, "spec/relay/v2.json"), "utf8"));
if (typeof input !== "object" || input === null || !("constants" in input) || !("kinds" in input) || !("failures" in input) || !("vectors" in input)) throw new Error("Invalid relay specification");

function entries(value: unknown): readonly (readonly [string, number])[] {
  if (typeof value !== "object" || value === null) throw new Error("Invalid relay constants");
  return Object.entries(value).map(([key, number]: [string, unknown]) => {
    if (!/^[A-Z_]+$/u.test(key) || typeof number !== "number" || !Number.isSafeInteger(number) || number < 1) throw new Error("Invalid relay constant");
    return [key, number] as const;
  });
}

function failureCodes(value: unknown): readonly string[] {
  if (!Array.isArray(value)) throw new Error("Invalid failure codes");
  const codes = value.map((code: unknown) => {
    if (typeof code !== "string" || !/^[a-z]+(?:-[a-z]+)*$/u.test(code)) throw new Error("Invalid failure codes");
    return code;
  });
  if (new Set(codes).size !== codes.length) throw new Error("Invalid failure codes");
  return codes;
}

const constants = entries(input.constants);
const kinds = entries(input.kinds);
const failures = failureCodes(input.failures);
const ts = [
  "// Generated by scripts/generate-relay-protocol.ts from spec/relay/v2.json.",
  ...constants.map(([key, value]) => `export const RELAY_${key === "HEADER" ? "HEADER_BYTES" : key} = ${value};`),
  `export const RelayKind = { ${kinds.map(([key, value]) => `${key}: ${value}`).join(", ")} } as const;`,
  `export const RELAY_FAILURES = [${failures.map(code => JSON.stringify(code)).join(", ")}] as const;`,
  "export type RelayFailureReason = typeof RELAY_FAILURES[number];",
  "",
].join("\n");
const vectors = `${JSON.stringify(input.vectors, null, 2)}\n`;
const outputs = new Map([
  ["packages/sdk/src/runtime/workers/relay-generated.ts", ts],
  ["packages/sdk/src/runtime/workers/fixtures/relay-v2.json", vectors],
]);
for (const [file, content] of outputs) {
  const path = resolve(root, file);
  if (process.argv.includes("--check")) {
    if (await readFile(path, "utf8") !== content) throw new Error(`Relay protocol drift: ${file}`);
  } else {
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, content);
  }
}
