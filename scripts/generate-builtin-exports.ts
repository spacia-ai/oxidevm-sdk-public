// Generates the export names of every built-in module of the pinned Node.js 24.18.1 and Bun
// 1.3.14 (ADR 0026): the fast path compares the built-ins it provides against them, so a program
// that touched a real export the fast path lacks and then failed is remembered by that exact name
// and runs in full Linux next time. The runtimes are the managed image's own binaries: the root
// filesystem archive is imported as a temporary image, probed, and that one image is removed.
// Usage: node scripts/generate-builtin-exports.ts <root filesystem archive> [--check]
import assert from "node:assert/strict";
import { execFile } from "node:child_process";
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { promisify } from "node:util";

const execute = promisify(execFile);
const root = resolve(import.meta.dirname, "..");
const output = resolve(root, "packages/sdk/src/runtime/workers/assistance/builtin-exports.generated.ts");
const RUNTIMES = { node: { executable: "/usr/bin/node", version: "v24.18.1" }, bun: { executable: "/usr/local/bin/bun", version: "1.3.14" } } as const;

// Every public built-in module and the names its CommonJS export enumerates, sorted.
const PROBE = `const builtins = require("node:module").builtinModules.filter(name => !name.startsWith("_") && !name.startsWith("node:") && !name.startsWith("bun:"));
const exports = {};
for (const name of [...new Set(builtins)].sort()) {
  let value;
  try { value = require("node:" + name); } catch { continue; }
  if ((typeof value !== "object" && typeof value !== "function") || value === null) continue;
  exports[name] = Object.keys(value).filter(key => /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(key)).sort();
}
process.stdout.write(JSON.stringify({ version: process.versions.bun ?? process.version, exports }));`;

const args = process.argv.slice(2), check = args.includes("--check");
const archive = args.find(value => !value.startsWith("--"));
assert(archive !== undefined, "usage: node scripts/generate-builtin-exports.ts <root filesystem archive> [--check]");
const archiveSHA256 = createHash("sha256").update(await readFile(archive)).digest("hex");
const tag = `oxidevm-builtin-exports:${archiveSHA256.slice(0, 16)}`;

async function probe(runtime: keyof typeof RUNTIMES): Promise<Readonly<Record<string, readonly string[]>>> {
  const { executable, version } = RUNTIMES[runtime];
  const result = await execute("docker", ["run", "--rm", "--network", "none", "--user", "1000:1000", "--env", "HOME=/tmp", tag, executable, "-e", PROBE], { timeout: 120_000, maxBuffer: 16 * 1024 * 1024 });
  const value: unknown = JSON.parse(result.stdout);
  assert(typeof value === "object" && value !== null && "version" in value && "exports" in value, `${runtime} probe output`);
  assert.equal(value.version, version, `${runtime} must be the pinned build`);
  const exports = value.exports;
  assert(typeof exports === "object" && exports !== null);
  const decoded: Record<string, readonly string[]> = {};
  for (const [name, list] of Object.entries(exports)) {
    assert(/^[a-z][a-z0-9_/]*$/u.test(name) && Array.isArray(list) && list.every((key: unknown) => typeof key === "string"), `${runtime} ${name} exports`);
    decoded[name] = list.map(String);
  }
  return decoded;
}

await execute("docker", ["import", archive, tag], { timeout: 300_000 });
let node: Readonly<Record<string, readonly string[]>>, bun: Readonly<Record<string, readonly string[]>>;
try {
  node = await probe("node");
  bun = await probe("bun");
} finally {
  // Only the image this run imported; nothing else on the host is touched.
  await execute("docker", ["rmi", tag], { timeout: 60_000 });
}
const literal = (value: Readonly<Record<string, readonly string[]>>) => `{\n${Object.entries(value).map(([name, list]) => `  ${JSON.stringify(name)}: ${JSON.stringify(list)},`).join("\n")}\n}`;
const text = `// Generated by scripts/generate-builtin-exports.ts from the managed image's Node.js ${RUNTIMES.node.version} and Bun ${RUNTIMES.bun.version}
// (root filesystem archive ${archiveSHA256}). Do not edit.

/** The enumerable CommonJS exports of each public built-in module of the pinned Node.js. */
export const NODE_BUILTIN_EXPORTS: Readonly<Record<string, readonly string[]>> = ${literal(node)};

/** The same for the pinned Bun, whose node: modules differ in places. */
export const BUN_BUILTIN_EXPORTS: Readonly<Record<string, readonly string[]>> = ${literal(bun)};
`;
if (check) {
  assert.equal(await readFile(output, "utf8"), text, "builtin-exports.generated.ts is stale: run node scripts/generate-builtin-exports.ts");
  process.stdout.write("builtin exports are current\n");
} else {
  await writeFile(output, text);
  process.stdout.write(`${JSON.stringify({ output, node: Object.keys(node).length, bun: Object.keys(bun).length })}\n`);
}
